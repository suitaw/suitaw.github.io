/* 实心的那几个：不描边、直接填色（play 之类三角形描边不好看） */
const FILLED = {play:1, shock:1};

function svg(key, size, cls){
  const d = P[key];
  if(!d) return '';
  const s = size || 24;
  const f = FILLED[key];
  return '<svg class="'+(cls||'ei')+'" width="'+s+'" height="'+s+'" viewBox="0 0 24 24" '+
    'fill="'+(f?'currentColor':'none')+'" stroke="'+(f?'none':'currentColor')+'" '+
    'stroke-width="'+SW+'" stroke-linecap="round" stroke-linejoin="round" '+
    'aria-hidden="true" focusable="false">'+d+'</svg>';
}

/* 章号 → 图标 key；节号 → 图标 key。找不到就退回一个通用的 */
